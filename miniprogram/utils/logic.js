/* 某点在区间走廊带内? (供出发地/目的地/中转站判定) */
function inIntervalBelt(S, H, P, tLo, tHi, band) {
  const L = dist(S, H);
  if (L < 15) return true; // 退化区间: 无走廊概念, 由直达50km/中转绕行规则约束
  const { t, p } = corridor(S, H, P);
  return t >= tLo && t <= tHi && p <= band;
}

